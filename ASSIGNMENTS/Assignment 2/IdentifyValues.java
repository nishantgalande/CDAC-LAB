public class IdentifyValues{
	
	static byte a;
	static short b;
	static int c;
	static long d;
	static float e;
	static double f;
	static char g;
	static boolean h;
	
	
	public static void main(String[] args){
		System.out.println("Byte: " + IdentifyValues.a);
		System.out.println("Short: " + IdentifyValues.b);
		System.out.println("Int: " + IdentifyValues.c);
		System.out.println("Long: " + IdentifyValues.d);
		System.out.println("Float: " + IdentifyValues.e);
		System.out.println("Double: " + IdentifyValues.f);
		System.out.println("Character: " + IdentifyValues.g);
		System.out.println("Boolean: " + IdentifyValues.h);
	}
}